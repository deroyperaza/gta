/** A line from `lines` that hasn't been heard yet in pool `key`; once every line has been heard, the pool starts over. */
export function pickLine(key: string, lines: string[]): string {
  const heard = (state.d.heard ??= {});
  let used = heard[key] ?? [];
  if (used.length >= lines.length) used = [];
  const open = lines.map((_, i) => i).filter((i) => !used.includes(i));
  const i = open[Math.floor(Math.random() * open.length)];
  heard[key] = [...used, i];
  return lines[i];
}

/** What a random person says when you chat: mostly their neighborhood, sometimes the whole borough. */
export function streetLine(district: District): string {
  const local = STREET_LINES[district] ?? GENERAL;
  const heard = state.d.heard ?? {};
  const localLeft = local.length - (heard[`d:${district}`]?.length ?? 0), allLeft = GENERAL.length - (heard.all?.length ?? 0);
  return Math.random() < localLeft / Math.max(1, localLeft + allLeft) ? pickLine(`d:${district}`, local) : pickLine('all', GENERAL);
}

export const flyerLine = () => pickLine('flyer', ALL_FLYER_LINES);
