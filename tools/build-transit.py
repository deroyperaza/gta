#!/usr/bin/env python3
"""
Builds src/world/transitData.ts from the MTA's own station list (NY Open Data, "MTA Subway Stations",
dataset 39hk-dx4f: https://data.ny.gov/Transportation/MTA-Subway-Stations/39hk-dx4f).

    curl -L "https://data.ny.gov/api/views/39hk-dx4f/rows.csv?accessType=DOWNLOAD" -o stations.csv
    python3 tools/build-transit.py stations.csv > src/world/transitData.ts

Brooklyn rows only. Stations in one complex (Atlantic Av-Barclays Ctr, Jay St-MetroTech...) become one stop
with every line that serves it. Each line's stops are put in order by walking from one end to the other.
ADA comes straight from the MTA's column: 1 = fully accessible, 2 = partly (one direction), 0 = not.
"""
import csv, json, math, sys
from collections import defaultdict

rows = [r for r in csv.DictReader(open(sys.argv[1], newline='')) if r['Borough'] == 'Bk']

complexes = {}
for r in rows:
    cid = r['Complex ID']
    c = complexes.setdefault(cid, {'names': [], 'lat': [], 'lng': [], 'routes': [], 'ada': []})
    c['names'].append(r['Stop Name']); c['lat'].append(float(r['GTFS Latitude'])); c['lng'].append(float(r['GTFS Longitude']))
    for rt in r['Daytime Routes'].split():
        if rt not in c['routes']: c['routes'].append(rt)
    c['ada'].append(int(r['ADA'] or 0))

def name_of(c):
    # The longest name usually carries the whole complex ("Atlantic Av-Barclays Ctr")
    return max(c['names'], key=len)

stations = []
for cid, c in complexes.items():
    lat = sum(c['lat']) / len(c['lat']); lng = sum(c['lng']) / len(c['lng'])
    ada = 1 if all(a == 1 for a in c['ada']) else (2 if any(a >= 1 for a in c['ada']) else 0)
    stations.append({'id': cid, 'name': name_of(c), 'lat': round(lat, 6), 'lng': round(lng, 6),
                     'routes': sorted(c['routes'], key=lambda s: (not s.isdigit(), s)), 'ada': ada})
stations.sort(key=lambda s: s['name'])
by_id = {s['id']: s for s in stations}

def dist(a, b):
    k = math.cos(math.radians(40.65))
    return math.hypot((a['lat'] - b['lat']), (a['lng'] - b['lng']) * k)

lines = {}
for rt in sorted({r for s in stations for r in s['routes']}):
    st = [s for s in stations if rt in s['routes']]
    if len(st) < 2:
        lines[rt] = [s['id'] for s in st]; continue
    # Endpoints: the farthest-apart pair. Start from the northern one (toward Manhattan) and walk to the nearest stop each time.
    a, b = max(((p, q) for p in st for q in st), key=lambda pq: dist(*pq))
    cur = a if a['lat'] >= b['lat'] else b
    order, left = [cur], [s for s in st if s is not cur]
    while left:
        nxt = min(left, key=lambda s: dist(cur, s)); order.append(nxt); left.remove(nxt); cur = nxt
    # Straighten it out (2-opt on an open path): nearest-neighbor walks zigzag in tight clusters like Downtown
    d = lambda i, j: dist(order[i], order[j]) if 0 <= i < len(order) and 0 <= j < len(order) else 0.0
    better = True
    while better:
        better = False
        for i in range(len(order)):
            for j in range(i + 1, len(order)):
                old = d(i - 1, i) + d(j, j + 1); new = d(i - 1, j) + d(i, j + 1)
                if new < old - 1e-9:
                    order[i:j + 1] = reversed(order[i:j + 1]); better = True
    if order[0]['lat'] < order[-1]['lat']: order.reverse()  # north/Manhattan end first
    lines[rt] = [s['id'] for s in order]

n = len(stations); full = sum(1 for s in stations if s['ada'] == 1); part = sum(1 for s in stations if s['ada'] == 2)
print('// GENERATED by tools/build-transit.py from the MTA Subway Stations dataset (NY Open Data 39hk-dx4f). Do not edit by hand.')
print(f'// Brooklyn: {n} stations (complexes). Fully accessible: {full}. Partly: {part}. Not accessible: {n - full - part}.')
print('export interface Station { id: string; name: string; lat: number; lng: number; routes: string[]; ada: 0 | 1 | 2 }')
print('export const STATIONS: Station[] = ' + json.dumps(stations, separators=(',', ':')) + ';')
print('/** Each line\'s Brooklyn stops in order, north/Manhattan end first */')
print('export const LINES: Record<string, string[]> = ' + json.dumps(lines, separators=(',', ':')) + ';')
print(f'export const ADA_STATS = {{ total: {n}, full: {full}, partial: {part} }};')
